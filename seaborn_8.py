import pandas as pd
import seaborn as sns
import matplotlib.pyplot as plt

data = {
    'User': [f'User{i}' for i in range(1, 21)],
    'Followers': [
        500, 1200, 2500, 800, 4000,
        1500, 3000, 700, 5000, 2200,
        1800, 6000, 3500, 900, 4500,
        2800, 1100, 5500, 2000, 3800
    ],
    'Posts': [
        50, 120, 200, 80, 350,
        140, 250, 60, 400, 180,
        160, 500, 300, 90, 370,
        230, 100, 450, 170, 320
    ]
}

df = pd.DataFrame(data)

sns.scatterplot(
    data=df,
    x='Followers',
    y='Posts'
)

plt.title('Instagram Followers vs Posts')
plt.xlabel('Number of Followers')
plt.ylabel('Number of Posts')
plt.show()

