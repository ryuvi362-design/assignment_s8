np.random.seed(42)

youtube_hours = np.random.randint(1, 8, 25)

exam_scores = (
    95 - youtube_hours * 6
    + np.random.randint(-8, 9, 25)
)

exam_scores = np.clip(exam_scores, 20, 100)

df = pd.DataFrame({
    'YouTube_Hours': youtube_hours,
    'Exam_Score': exam_scores
})

sns.regplot(
    data=df,
    x='YouTube_Hours',
    y='Exam_Score'
)

plt.title('YouTube Hours vs Exam Scores')
plt.xlabel('Hours Spent on YouTube per Day')
plt.ylabel('Exam Score')
plt.show()